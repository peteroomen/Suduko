import { createHash } from 'node:crypto';
import { cp, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const projectDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');

async function filesUnder(directory, base = directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await filesUnder(path, base));
    else if (entry.isFile()) files.push(relative(base, path).replaceAll('\\', '/'));
    else throw new Error(`Build input must be an ordinary file or directory: ${path}`);
  }
  return files;
}

export function serviceWorkerSource(version, files) {
  return `// Generated by scripts/build.mjs. Update content version: ${version}\n` +
`const CACHE = 'suduko-shell-${version}';
const PRECACHE = ${JSON.stringify(files)};
self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(PRECACHE)));
  // Deliberately do not skipWaiting: an active puzzle keeps its coherent app version.
});
self.addEventListener('activate', event => {
  event.waitUntil(caches.keys().then(keys => Promise.all(
    keys.filter(key => key.startsWith('suduko-shell-') && key !== CACHE)
      .map(key => caches.delete(key))
  )));
});
self.addEventListener('fetch', event => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin) return;
  if (request.mode === 'navigate') {
    event.respondWith(caches.open(CACHE).then(async cache => {
      return await cache.match('/index.html') || fetch(request);
    }));
    return;
  }
  if (PRECACHE.includes(url.pathname)) {
    event.respondWith(caches.open(CACHE).then(async cache => {
      return await cache.match(url.pathname) || fetch(request);
    }));
  }
});
`;
}

export async function build({ output = join(projectDir, 'dist') } = {}) {
  output = resolve(output);
  if (output === projectDir || projectDir.startsWith(output + '/')) {
    throw new Error('Build output cannot overwrite the project or its ancestors.');
  }
  if (['src', 'public', 'scripts', 'tests', '.git'].some(name => output === join(projectDir, name) || output.startsWith(join(projectDir, name) + '/'))) {
    throw new Error('Build output cannot overwrite a source directory.');
  }
  await readFile(join(projectDir, 'index.html')); // Fail before cleaning output if app is missing.
  await rm(output, { recursive: true, force: true });
  await mkdir(output, { recursive: true });
  await cp(join(projectDir, 'index.html'), join(output, 'index.html'));
  await cp(join(projectDir, 'src'), join(output, 'src'), { recursive: true });
  await cp(join(projectDir, 'public'), output, { recursive: true });
  const paths = (await filesUnder(output)).sort();
  const digests = {};
  const versionHash = createHash('sha256');
  versionHash.update(serviceWorkerSource('', []));
  for (const path of paths) {
    const bytes = await readFile(join(output, path));
    digests['/' + path] = createHash('sha256').update(bytes).digest('hex');
    versionHash.update(path).update('\0').update(bytes).update('\0');
  }
  const version = versionHash.digest('hex').slice(0, 20);
  const files = [...paths.map(path => '/' + path), '/service-worker.js'].sort();
  const worker = serviceWorkerSource(version, files);
  await writeFile(join(output, 'service-worker.js'), worker);
  digests['/service-worker.js'] = createHash('sha256').update(worker).digest('hex');
  await writeFile(join(output, 'build-manifest.json'), JSON.stringify({ version, files, digests }, null, 2) + '\n');
  return { version, files, output };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = await build();
  console.log(`Built ${result.files.length} local files into dist (version ${result.version}).`);
}
